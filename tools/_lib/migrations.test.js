/* migrations.test.js - the checker, and the manifest it cannot drift from.

     node tools/_lib/migrations.test.js            check
     node tools/_lib/migrations.test.js --write    regenerate the manifest

   WHY THIS FILE GENERATES THE MANIFEST. A hand-kept list of probes drifts
   the first time somebody adds a migration and forgets, and a checker
   that silently stops covering one is worse than no checker. So the list
   is parsed out of supabase/*.sql here, every run, and compared to what
   is committed in migrations.data.js. Adding a migration fails the suite
   until the manifest is regenerated. That failure is the feature.

   THE RULE: it must never be able to say "all applied" when it could not
   check. A migration that creates no table and no column is UNVERIFIABLE
   - not applied, not missing, unknown - and the summary refuses to call
   a run clean while any remain unknown, or while any probe was refused
   or unreachable. Proved by breaking, below.
*/
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..', '..');
const SQLDIR = path.join(ROOT, 'supabase');
const DATA = path.join(__dirname, 'migrations.data.js');
const M = require(path.join(__dirname, 'migrations.js'));

let pass = 0, fail = 0;
const is = (label, got, want) => {
  const a = JSON.stringify(got), b = JSON.stringify(want);
  if (a === b) { pass++; return; }
  fail++; console.log('FAIL ' + label + '\n  got  ' + a + '\n  want ' + b);
};

/* ---- the parse ------------------------------------------------------
   Comments are stripped first, or 047's closing paragraph - which names
   pu_reports on purpose - would be read as a statement. The probe is the
   cheapest read of something the migration creates: a column it adds, or
   failing that a table it creates. */
function parse() {
  const files = fs.readdirSync(SQLDIR).filter(f => /\.sql$/.test(f)).sort();
  const probes = [], unverifiable = [];
  for (const f of files) {
    const src = fs.readFileSync(path.join(SQLDIR, f), 'utf8').split('\r\n').join('\n')
      .split('\n').filter(l => !/^\s*--/.test(l)).join('\n');

    const cols = [...src.matchAll(
      /alter\s+table\s+(?:public\.)?([a-z0-9_]+)\s+add\s+column\s+(?:if\s+not\s+exists\s+)?([a-z0-9_]+)/gi)]
      .map(m => ({ table: m[1], col: m[2] }));
    const tables = [...src.matchAll(
      /create\s+table\s+(?:if\s+not\s+exists\s+)?(?:public\.)?([a-z0-9_]+)/gi)].map(m => m[1]);

    /* A COLUMN IS BETTER EVIDENCE THAN A TABLE, and 044 is why: it adds
       prev_state to a table 036 already created, so probing the table
       would have said "applied" for a migration that had not run. The
       column it adds is the only thing that distinguishes them. */
    if (cols.length) probes.push({ file: f, table: cols[0].table, col: cols[0].col });
    else if (tables.length) probes.push({ file: f, table: tables[0], col: null });
    else unverifiable.push({ file: f,
      why: 'creates no table and no column - policies, data or functions only. ' +
           'Functions are not probed by calling them, because some of them write.' });
  }
  return { probes, unverifiable };
}

const fresh = parse();

/* ---- --write --------------------------------------------------------- */
if (process.argv.includes('--write')) {
  const body =
    '/* GENERATED by migrations.test.js - do not edit by hand.\n' +
    '   Run: node tools/_lib/migrations.test.js --write\n' +
    '   The test regenerates this on every run and fails if it differs, so a\n' +
    '   migration added without refreshing this file breaks the suite. */\n' +
    '(function (root, factory) {\n' +
    "  if (typeof module === 'object' && module.exports) module.exports = factory();\n" +
    '  else { root.MIGRATION_DATA = factory();\n' +
    '         if (root.Migrations) root.Migrations.load(root.MIGRATION_DATA.probes, root.MIGRATION_DATA.unverifiable); }\n' +
    "}(typeof self !== 'undefined' ? self : this, function () {\n" +
    '  return ' + JSON.stringify(fresh, null, 2).split('\n').join('\n  ') + ';\n' +
    '}));\n';
  fs.writeFileSync(DATA, body);
  console.log('wrote ' + DATA + ' - ' + fresh.probes.length + ' probes, ' +
              fresh.unverifiable.length + ' unverifiable');
  process.exit(0);
}

/* ---- 1. the manifest matches the folder ----------------------------- */
is('the manifest exists', fs.existsSync(DATA), true);
const DATA_JS = require(DATA);
is('EVERY MIGRATION IS ACCOUNTED FOR, as a probe or as unverifiable',
   DATA_JS.probes.length + DATA_JS.unverifiable.length,
   fs.readdirSync(SQLDIR).filter(f => /\.sql$/.test(f)).length);
is('and the committed manifest is what the folder parses to now',
   JSON.stringify(DATA_JS), JSON.stringify(fresh));
is('there are enough migrations for that to mean something',
   fresh.probes.length > 20, true);

/* 044 is the incident this exists for: a column on a table 036 created */
const p044 = fresh.probes.find(p => /^044_/.test(p.file));
is('044 is probed by the COLUMN it adds, not the table it does not',
   p044 && [p044.table, p044.col], ['wh24_tickets', 'prev_state']);
const p036 = fresh.probes.find(p => /^036_/.test(p.file));
is('while 036 is probed by the table it creates',
   p036 && p036.col, null);

/* ---- 2. the states ---------------------------------------------------- */
is('a missing table reads as missing',
   M.classify({ message: 'Could not find the table \'public.pu_reports\' in the schema cache' }), 'missing');
is('a missing column reads as missing',
   M.classify({ message: 'column wh24_tickets.prev_state does not exist' }), 'missing');
is('A SIGN-IN PROBLEM IS NOT "applied"',
   M.classify({ message: 'JWT expired' }), 'refused');
is('and neither is a dead network',
   M.classify({ message: 'Failed to fetch' }), 'unreachable');
is('anything unrecognised is an error, not a pass',
   M.classify({ message: 'something nobody has seen before' }), 'error');

/* ---- 3. THE RULE: it cannot say all-applied when it could not check -- */
(async () => {
  M.load(fresh.probes, fresh.unverifiable);

  {
    /* everything answers cleanly */
    const rows = await M.check(async () => ({ error: null }));
    const s = M.summary(rows);
    is('every probe and every unverifiable is reported',
       rows.length, fresh.probes.length + fresh.unverifiable.length);
    is('IT IS NOT CLEAN WHILE ANYTHING IS UNVERIFIABLE', s.clean, false);
    is('and says so in the sentence', /cannot be checked at all/.test(s.line), true);
    is('while still counting what it did check', s.applied, fresh.probes.length);
  }
  {
    /* one missing */
    const target = fresh.probes[fresh.probes.length - 1];
    const rows = await M.check(async (t, c) =>
      (t === target.table && c === target.col)
        ? { error: { message: 'column ' + t + '.' + c + ' does not exist' } }
        : { error: null });
    const s = M.summary(rows);
    is('A MISSING MIGRATION IS NAMED', s.missing, [target.file]);
    is('and leads the sentence', /HAS NOT BEEN RUN/.test(s.line), true);
    is('and the run is not clean',  s.clean, false);
  }
  {
    /* THE ONE THAT MATTERS: the session has expired, so nothing is known */
    const rows = await M.check(async () => ({ error: { message: 'JWT expired' } }));
    const s = M.summary(rows);
    is('A REFUSED PROBE IS NEVER COUNTED AS APPLIED', s.applied, 0);
    is('the run is not clean',   s.clean, false);
    is('AND THE SENTENCE SAYS IT COULD NOT CHECK',
       /COULD NOT CHECK/.test(s.line) && /Nothing here says the rest are fine/.test(s.line), true);
  }
  {
    /* a probe that throws rather than returning an error */
    const rows = await M.check(async () => { throw new Error('Failed to fetch'); });
    const s = M.summary(rows);
    is('a thrown probe is unreachable, not applied', s.applied, 0);
    is('and the run is not clean', s.clean, false);
  }
  {
    /* an empty probe list must not read as a clean bill of health */
    M.load([], []);
    const s = M.summary(await M.check(async () => ({ error: null })));
    is('NO PROBES IS NOT ALL CLEAR', s.clean, false);
    is('and says nothing was checked', /NOTHING WAS CHECKED/.test(s.line), true);
    M.load(fresh.probes, fresh.unverifiable);
  }
  {
    /* the only shape that may say everything is applied */
    M.load(fresh.probes, []);
    const s = M.summary(await M.check(async () => ({ error: null })));
    is('with nothing unverifiable and nothing missing, it may say so', s.clean, true);
    is('and does',  /All \d+ migrations are applied\./.test(s.line), true);
    M.load(fresh.probes, fresh.unverifiable);
  }

  /* ---- 4. the asker builds the cheapest possible read ---------------- */
  {
    const seen = [];
    const ask = M.asker(t => ({ select: c => ({ limit: n => { seen.push([t, c, n]); return { error: null }; } }) }));
    await ask('wh24_tickets', 'prev_state');
    await ask('goals', null);
    is('one column, one row', seen[0], ['wh24_tickets', 'prev_state', 1]);
    is('and a table-only probe asks for anything, one row', seen[1], ['goals', '*', 1]);
  }

  console.log('\n' + pass + ' passed, ' + fail + ' failed\n');
  process.exit(fail ? 1 : 0);
})();
