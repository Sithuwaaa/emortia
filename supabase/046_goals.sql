-- WHOSE GOALS THESE ARE IS THE WHOLE DESIGN.
--
-- Every other table here is one shared estate: tickets, materials, the team.
-- This one is not. A goal is personal - what somebody is saving for, and how
-- far off it is - so the row carries its owner and the policy is "yours and
-- nobody else's", including mine. That is also what the entry in FEATURES
-- promises: opening the tool lets somebody keep their own list and never
-- shows them anybody else's.
--
-- The id is TEXT and generated by the browser, not a uuid default. The tool
-- shipped local-only first, so ids already exist in people's browsers, and
-- keeping the same shape means a local list can be pushed up as-is instead
-- of being renumbered on the way.

create table if not exists goals (
  id         text primary key,
  owner      uuid not null default auth.uid(),
  name       text not null,
  cat        text not null default 'self',
  target     numeric not null default 0,     -- what it costs; 0 means no price
  saved      numeric not null default 0,     -- put aside so far
  month      smallint,                       -- 0-11, or null for "any time"
  year       smallint not null,
  note       text,
  done       boolean not null default false,
  updated_at timestamptz not null default now()
);

create index if not exists goals_owner_year_idx on goals (owner, year);

alter table goals enable row level security;

drop policy if exists "goals_own" on goals;

-- One policy, both directions. A select that could read somebody else's row
-- and an insert that could write one are the same mistake, so they are the
-- same rule rather than two that can drift apart.
create policy "goals_own" on goals
  for all
  using      (auth.uid() = owner)
  with check (auth.uid() = owner);

-- The display currency. One row per person, which is why it is not a column
-- on `goals` - it belongs to the owner, not to any one goal, and carrying it
-- on every row would be the same fact stored forty times.
create table if not exists goal_prefs (
  owner      uuid primary key default auth.uid(),
  cur        text not null default 'Rs',
  updated_at timestamptz not null default now()
);

alter table goal_prefs enable row level security;

drop policy if exists "goal_prefs_own" on goal_prefs;

create policy "goal_prefs_own" on goal_prefs
  for all
  using      (auth.uid() = owner)
  with check (auth.uid() = owner);

-- so a goal ticked off on the phone leaves the laptop too
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and tablename = 'goals'
  ) then
    alter publication supabase_realtime add table goals;
  end if;
end $$;
